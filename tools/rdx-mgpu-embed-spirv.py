# Turns SPIR-V files into one C header of uint32_t arrays (the same layout as afmf-linux's
# cmake/embed_spirv.cmake): afmf_interpolate_rgba8.spv -> afmf_interpolate_rgba8_spv[] and
# afmf_interpolate_rgba8_spv_size. Usage: rdx-mgpu-embed-spirv.py OUT.h IN.spv...
import os
import re
import struct
import sys


def main():
    if len(sys.argv) < 3:
        sys.exit("usage: rdx-mgpu-embed-spirv.py OUT.h IN.spv...")
    out = ["/* Generated by tools/rdx-mgpu-embed-spirv.py; do not edit. */", "#pragma once",
           "#include <stddef.h>", "#include <stdint.h>", ""]
    for path in sys.argv[2:]:
        data = open(path, "rb").read()
        if len(data) % 4:
            sys.exit(f"{path}: not a SPIR-V module")
        sym = re.sub(r"[^A-Za-z0-9]", "_", os.path.basename(path))
        words = struct.unpack(f"<{len(data) // 4}I", data)
        body = ",".join(f"0x{w:08x}" for w in words)
        out.append(f"static const uint32_t {sym}[] = {{{body}}};")
        out.append(f"static const size_t {sym}_size = {len(words)} * sizeof(uint32_t);")
        out.append("")
    tmp = sys.argv[1] + ".tmp"
    with open(tmp, "w") as f:
        f.write("\n".join(out))
    os.replace(tmp, sys.argv[1])


if __name__ == "__main__":
    main()
